export function getRandomDialogueForPreset(presetTitle: string): string {
  const dialogues = PRESET_DIALOGUES[presetTitle];
  if (!dialogues || dialogues.length === 0) {
    // Fallback search by key substring
    const keys = Object.keys(PRESET_DIALOGUES);
    const matchedKey = keys.find(k => presetTitle.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(presetTitle.toLowerCase()));
    if (matchedKey && PRESET_DIALOGUES[matchedKey]?.length > 0) {
      const list = PRESET_DIALOGUES[matchedKey];
      return list[Math.floor(Math.random() * list.length)];
    }
    return "";
  }
  return dialogues[Math.floor(Math.random() * dialogues.length)];
}

export function getDialogueByPresetIndex(presetTitle: string, index: number): string {
  let dialogues = PRESET_DIALOGUES[presetTitle];
  if (!dialogues || dialogues.length === 0) {
    const keys = Object.keys(PRESET_DIALOGUES);
    const matchedKey = keys.find(k => presetTitle.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(presetTitle.toLowerCase()));
    if (matchedKey) dialogues = PRESET_DIALOGUES[matchedKey];
  }
  if (!dialogues || dialogues.length === 0) return "";
  const safeIndex = Math.abs(index) % dialogues.length;
  return dialogues[safeIndex];
}

export function saveGeneratedDialogueToPreset(presetTitle: string, dialogueText: string) {
  if (!presetTitle || !dialogueText || !dialogueText.trim()) return;
  const clean = dialogueText.trim();
  if (!PRESET_DIALOGUES[presetTitle]) {
    PRESET_DIALOGUES[presetTitle] = [];
  }
  if (!PRESET_DIALOGUES[presetTitle].includes(clean)) {
    PRESET_DIALOGUES[presetTitle].push(clean);
  }
}
